#include "test_support.hpp"

#include "vex/backend.hpp"
#include "vex/llvm_backend.hpp"

#include <memory>
#include <string>
#include <string_view>

namespace {

vex::IRValue value(const vex::IRValueId id, const vex::IRType type) {
    return vex::IRValue{id, type, {}};
}

vex::IRModule nested_fixed_stack_module() {
    vex::IRFunction worker;
    worker.name = "worker";
    worker.return_type = vex::IRType::Void;
    worker.entry_block = 0;
    for (vex::IRValueId id = 1; id <= 3; ++id) {
        vex::IRValue aggregate = vex::ir_make_array_value(vex::IRType::Int, {256u, 128u});
        aggregate.id = id;
        worker.parameters.push_back({"matrix" + std::to_string(id), aggregate});
    }
    vex::IRBlock entry;
    entry.id = 0;
    entry.name = "entry";
    entry.terminator = vex::IRTerminator{vex::IRReturn{}, {}};
    worker.blocks.push_back(entry);
    vex::IRModule module;
    module.functions.push_back(worker);
    return module;
}

vex::IRModule simple_main_module() {
    vex::IRBlock entry;
    entry.id = 0;
    entry.name = "entry";
    vex::IRInstruction literal;
    literal.op = vex::IROp::Constant;
    literal.result = value(1, vex::IRType::Int);
    literal.immediate = "42";
    entry.instructions.push_back(literal);
    vex::IRInstruction say;
    say.op = vex::IROp::Say;
    say.operands = {1};
    entry.instructions.push_back(say);
    entry.terminator = vex::IRTerminator{vex::IRReturn{}, {}};
    vex::IRFunction main;
    main.name = "main";
    main.return_type = vex::IRType::Void;
    main.entry_block = 0;
    main.blocks.push_back(entry);
    vex::IRModule module;
    module.functions.push_back(main);
    return module;
}

bool has_code(const vex::BackendResult& result, const std::string_view code) {
    for (const vex::Diagnostic& diagnostic : result.diagnostics) {
        if (diagnostic.code == code) return true;
    }
    return false;
}

void test_llvm_backend_is_registered(TestContext& tests) {
    const std::unique_ptr<vex::Backend> backend =
        vex::create_backend(vex::BackendKind::LLVM);
    tests.check(backend != nullptr, "backend factory registers the LLVM backend");
    if (!backend) return;
    tests.check(backend->name() == std::string_view{"llvm"},
                "LLVM backend identifies itself through the common interface");
}

vex::IRModule integer_main_module() {
    vex::IRModule module = simple_main_module();
    module.functions.front().return_type = vex::IRType::Int;
    module.functions.front().blocks.front().terminator =
        vex::IRTerminator{vex::IRReturn{1}, {}};
    return module;
}

void test_llvm_backend_emits_ir(TestContext& tests) {
    const vex::BackendResult result = vex::LLVMBackend{}.emit(simple_main_module());
    tests.check(!result.has_errors(), "LLVM backend accepts valid verified IR");
    tests.check(result.output.find("define i32 @main()") != std::string::npos,
                "LLVM backend emits a native entry-point wrapper");
    tests.check(result.output.find("define internal void @vex_fn_main()") != std::string::npos,
                "LLVM backend emits the VEX main function");
    tests.check(result.output.find("@printf") != std::string::npos,
                "LLVM backend lowers say to its runtime output");
    tests.check(result.output.find("add i64 0, 42") != std::string::npos,
                "LLVM backend preserves integer constants");
    tests.check(result.output.find("Generated by the VEX LLVM backend") != std::string::npos,
                "LLVM output is distinguishable from C source");
    const auto concat_start = result.output.find("define internal { ptr, i64 } @vex_string_concat");
    const auto concat_end = result.output.find("define internal { ptr, i64 } @vex_string_join", concat_start);
    const bool has_concat_helper = concat_start != std::string::npos &&
                                   concat_end != std::string::npos;
    tests.check(has_concat_helper, "LLVM backend emits its string concatenation runtime helper");
    if (has_concat_helper) {
        const std::string_view helper{result.output.data() + concat_start, concat_end - concat_start};
        const auto first_malloc = helper.find("call ptr @malloc(i64");
        tests.check(first_malloc != std::string_view::npos &&
                    helper.find("call ptr @malloc(i64", first_malloc + 1) == std::string_view::npos,
                    "LLVM string concatenation uses one allocation for metadata and bytes");
        tests.check(helper.find("ret { ptr, i64 } %right") != std::string_view::npos &&
                    helper.find("ret { ptr, i64 } %left") != std::string_view::npos,
                    "LLVM string concatenation returns the non-empty operand without allocating");
    }
}

void test_llvm_backend_guards_nested_fixed_stack_storage(TestContext& tests) {
    const vex::BackendResult result = vex::LLVMBackend{}.emit(nested_fixed_stack_module());
    tests.check(!result.has_errors(), "LLVM backend accepts nested fixed aggregate IR for target-layout checks");
    tests.check(result.output.find("getelementptr [256 x [128 x i64]], ptr null, i64 1") != std::string::npos,
                "LLVM backend derives nested aggregate allocation size from target data layout");
    tests.check(result.output.find("vex_stack_trap") != std::string::npos &&
                result.output.find("vex_stack_alloc_count") != std::string::npos,
                "LLVM backend checks the nested aggregate budget before dynamic stack allocation");
    tests.check(result.output.find("524288") != std::string::npos,
                "LLVM backend enforces the shared per-function aggregate budget");
}

void test_llvm_backend_checks_allocation_failures_and_exit_cleanup(TestContext& tests) {
    const vex::BackendResult result = vex::LLVMBackend{}.emit(integer_main_module());
    tests.check(!result.has_errors(), "LLVM backend accepts an integer-returning entry for cleanup verification");
    tests.check(result.output.find("%failed = icmp eq ptr %array, null") != std::string::npos &&
                result.output.find("%allocation_failed = icmp eq ptr %new_data, null") != std::string::npos &&
                result.output.find("%allocation_failed = icmp eq ptr %node, null") != std::string::npos,
                "LLVM runtime checks dynamic-array header, buffer, and string allocations");
    tests.check(result.output.find("call void @free(ptr %data)") != std::string::npos &&
                result.output.find("call void @free(ptr %current)") != std::string::npos &&
                result.output.find("call void @free(ptr %node)") != std::string::npos,
                "LLVM runtime releases tracked array buffers, headers, and string allocations");
    const std::size_t invalid_exit = result.output.find("vex_invalid_exit:");
    const std::size_t arrays = result.output.find("call void @vex_array_cleanup()", invalid_exit);
    const std::size_t strings = result.output.find("call void @vex_string_cleanup()", arrays);
    const std::size_t trap = result.output.find("call void @llvm.trap()", strings);
    tests.check(invalid_exit != std::string::npos && arrays > invalid_exit &&
                strings > arrays && trap > strings,
                "LLVM entry wrapper cleans tracked allocations before trapping on an invalid exit status");
}

void test_llvm_backend_rejects_invalid_entry_point(TestContext& tests) {
    vex::IRModule module = simple_main_module();
    module.functions.front().parameters.push_back(
        {"argument", value(2, vex::IRType::Int)});
    const vex::BackendResult result = vex::LLVMBackend{}.emit(module);
    tests.check(has_code(result, "LLVM002"),
                "LLVM backend diagnoses unsupported main parameters");
    tests.check(result.output.empty(),
                "LLVM backend does not return partial output after a code-generation error");
}

} // namespace

void run_llvm_backend_tests(TestContext& tests) {
    test_llvm_backend_is_registered(tests);
    test_llvm_backend_emits_ir(tests);
    test_llvm_backend_guards_nested_fixed_stack_storage(tests);
    test_llvm_backend_checks_allocation_failures_and_exit_cleanup(tests);
    test_llvm_backend_rejects_invalid_entry_point(tests);
}
