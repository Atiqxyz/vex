#include "test_support.hpp"

#include "vex/backend.hpp"
#include "vex/llvm_backend.hpp"

#include <memory>
#include <string_view>

namespace {

vex::IRValue value(const vex::IRValueId id, const vex::IRType type) {
    return vex::IRValue{id, type, {}};
}

vex::IRModule simple_main_module() {
    vex::IRBlock entry;
    entry.id = 0;
    entry.name = "entry";
    vex::IRInstruction literal;
    literal.op = vex::IROp::Constant;
    literal.result = value(1, vex::IRType::Int);
    literal.immediate = "42";
    entry.instructions.push_back(literal);
    vex::IRInstruction say;
    say.op = vex::IROp::Say;
    say.operands = {1};
    entry.instructions.push_back(say);
    entry.terminator = vex::IRTerminator{vex::IRReturn{}, {}};
    vex::IRFunction main;
    main.name = "main";
    main.return_type = vex::IRType::Void;
    main.entry_block = 0;
    main.blocks.push_back(entry);
    vex::IRModule module;
    module.functions.push_back(main);
    return module;
}

bool has_code(const vex::BackendResult& result, const std::string_view code) {
    for (const vex::Diagnostic& diagnostic : result.diagnostics) {
        if (diagnostic.code == code) return true;
    }
    return false;
}

void test_llvm_backend_is_registered(TestContext& tests) {
    const std::unique_ptr<vex::Backend> backend =
        vex::create_backend(vex::BackendKind::LLVM);
    tests.check(backend != nullptr, "backend factory registers the LLVM backend");
    if (!backend) return;
    tests.check(backend->name() == std::string_view{"llvm"},
                "LLVM backend identifies itself through the common interface");
}

void test_llvm_backend_emits_ir(TestContext& tests) {
    const vex::BackendResult result = vex::LLVMBackend{}.emit(simple_main_module());
    tests.check(!result.has_errors(), "LLVM backend accepts valid verified IR");
    tests.check(result.output.find("define i32 @main()") != std::string::npos,
                "LLVM backend emits a native entry-point wrapper");
    tests.check(result.output.find("define internal void @vex_fn_main()") != std::string::npos,
                "LLVM backend emits the VEX main function");
    tests.check(result.output.find("@printf") != std::string::npos,
                "LLVM backend lowers say to its runtime output");
    tests.check(result.output.find("add i64 0, 42") != std::string::npos,
                "LLVM backend preserves integer constants");
    tests.check(result.output.find("Generated by the VEX LLVM backend") != std::string::npos,
                "LLVM output is distinguishable from C source");
}

void test_llvm_backend_rejects_invalid_entry_point(TestContext& tests) {
    vex::IRModule module = simple_main_module();
    module.functions.front().parameters.push_back(
        {"argument", value(2, vex::IRType::Int)});
    const vex::BackendResult result = vex::LLVMBackend{}.emit(module);
    tests.check(has_code(result, "LLVM002"),
                "LLVM backend diagnoses unsupported main parameters");
    tests.check(result.output.empty(),
                "LLVM backend does not return partial output after a code-generation error");
}

} // namespace

void run_llvm_backend_tests(TestContext& tests) {
    test_llvm_backend_is_registered(tests);
    test_llvm_backend_emits_ir(tests);
    test_llvm_backend_rejects_invalid_entry_point(tests);
}
